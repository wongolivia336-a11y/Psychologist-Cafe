export type Grounding = "primary" | "mixed" | "cards-only";

export type Persona = {
  id: string;
  name: string;
  latin: string;
  years: string;
  /** 大堂里桌子的位置（百分比坐标，固定机位） */
  table: { x: number; y: number };
  /** v1 只点亮胡塞尔。其余桌子有人坐，但还坐不过去——绣湖式的「锁住的门」。 */
  unlocked: boolean;
  /** 绣湖式物件头：不画真人脸 */
  mask: string;
  maskNote: string;
  /** 检索哪些哲学家的语料。persona 与语料解耦，一个角色可挂多份语料。 */
  corpus: string[];
  grounding: Grounding;
  /** 语料真实性说明，前端如实展示，不糊弄用户 */
  groundingNote: string;
  tagline: string;
  /** 坐下时的开场白，随机取一句 */
  openings: string[];
  system: string;
};

